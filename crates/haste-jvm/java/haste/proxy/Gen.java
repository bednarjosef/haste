package haste.proxy;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.*;
import java.util.function.Predicate;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;
import org.objectweb.asm.commons.MethodRemapper;
import org.objectweb.asm.commons.SimpleRemapper;
import org.objectweb.asm.tree.*;

/**
 * Tier-2 proxy generator. Reads vanilla classes from the player's client jar (never shipped, never on the class
 * path) and writes same-name, same-signature classes whose method bodies are one of:
 * <ul>
 *   <li><b>impl</b>: a call to a public static method of a Haste class ({@code impl <owner> <class>}) with the same
 *       name and the descriptor {@code (<owner> this, args...)ret} (instance) or {@code (args...)ret} (static).
 *       This is how batched draw calls ({@code GuiGraphicsExtractor -> haste.gui.GfxImpl}) and Rust-backed state
 *       ({@code ItemStack -> haste.gui.StackImpl -> haste.rt.Native}) are wired;</li>
 *   <li><b>native</b>: a JNI native implemented in Rust;</li>
 *   <li><b>getter</b>: returns a (mirrored) Java field of the proxy;</li>
 *   <li><b>noop</b>: returns 0 / false / null (for subsystems Haste does not have, e.g. sound);</li>
 *   <li>otherwise a <b>stub</b> that records the method in {@code haste.rt.Unimplemented} and throws.</li>
 * </ul>
 * All vanilla fields are kept (final dropped on instance fields and non-constant statics), static initialisers
 * are dropped (static fields start null/0), constructors ignore their arguments, and the root of each hierarchy
 * gets {@code public long haste$handle}. Mixins targeting a generated class get their non-shadow members merged
 * (Phase 2; needs a mod jar).
 *
 * <p>Config ({@code proxies.conf}) lines:
 * <pre>
 *   class    &lt;internal&gt;                       generate it, its superclass chain and its non-real interfaces
 *   impl     &lt;internal&gt; &lt;impl class&gt;          wire every matching public static method of the impl class
 *   noop     &lt;owner&gt;#&lt;name&gt;&lt;desc&gt; | &lt;owner&gt;#*   return a default value (#* = every method without impl)
 *   native   &lt;owner&gt;#&lt;name&gt;&lt;desc&gt;
 *   getter   &lt;owner&gt;#&lt;name&gt;&lt;desc&gt;=&lt;field&gt;[:&lt;desc&gt;]
 *   statics  &lt;internal&gt;                       keep vanilla's static initialiser and static method bodies
 *   keep     &lt;owner&gt;#&lt;name&gt;[&lt;desc&gt;]           keep vanilla's body of a method (all overloads without desc)
 *   mixin    &lt;internal mixin class&gt;              (only with a mod jar)
 * </pre>
 */
public final class Gen implements Opcodes {
    /** Bump when the generated bytecode shape changes, so cached proxies are regenerated. */
    public static final int VERSION = 5;

    private final ZipFile client;
    private final ZipFile mod;
    private final Path implDir;
    private final Predicate<String> real;
    private final Map<String, String> how = new HashMap<>();             // owner#name+desc or owner#* -> kind
    private final Map<String, List<String[]>> implCandidates = new HashMap<>(); // owner#name -> {impl class, desc}
    private final Map<String, List<ClassNode>> mixinsByTarget = new HashMap<>();
    private final Map<String, ClassNode> cache = new HashMap<>();
    private final Set<String> roots = new LinkedHashSet<>();
    /** Classes whose static state is vanilla's (constants, codecs, keys): {@code <clinit>} and static bodies kept. */
    private final Set<String> statics = new HashSet<>();
    private final StringBuilder report = new StringBuilder();
    private int classes, methods, natives, getters, implCount, noops, stubs, merged, kept;

    /**
     * @param clientJar the player's client jar
     * @param modJar    a mod jar for {@code mixin} lines, or null
     * @param implDir   directory with compiled impl classes ({@code build/game})
     * @param real      internal names that stay real tier-3 classes: interfaces in this set are not generated
     */
    public Gen(Path clientJar, Path modJar, Path implDir, Predicate<String> real) throws IOException {
        this.client = new ZipFile(clientJar.toFile());
        this.mod = modJar == null ? null : new ZipFile(modJar.toFile());
        this.implDir = implDir;
        this.real = real;
    }

    /**
     * Generates the proxies for {@code conf} into {@code out} unless {@code out/.stamp} matches the inputs.
     * Writes into a temporary directory first and renames it, so concurrent processes never see half a set.
     * Returns a one-line summary.
     */
    public static String generateIfStale(Path clientJar, Path conf, Path implDir, Path out, Predicate<String> real, String realKey) throws Exception {
        String stamp = stamp(clientJar, conf, implDir, realKey);
        Path stampFile = out.resolve(".stamp");
        if (Files.isRegularFile(stampFile) && Files.readString(stampFile).equals(stamp)) return "proxies up to date in " + out;
        Files.createDirectories(out.getParent());
        Path tmp = out.resolveSibling(out.getFileName() + ".tmp-" + ProcessHandle.current().pid());
        deleteTree(tmp);
        Gen g = new Gen(clientJar, null, implDir, real);
        g.readConfig(Files.readAllLines(conf));
        String summary = g.run(tmp);
        Files.writeString(tmp.resolve("GENERATED.txt"), g.report.toString());
        Files.writeString(tmp.resolve(".stamp"), stamp);
        Path old = out.resolveSibling(out.getFileName() + ".old-" + ProcessHandle.current().pid());
        if (Files.exists(out)) Files.move(out, old);
        Files.move(tmp, out);
        deleteTree(old);
        return summary;
    }

    private static String stamp(Path clientJar, Path conf, Path implDir, String realKey) throws Exception {
        MessageDigest md = MessageDigest.getInstance("SHA-256");
        md.update(("v" + VERSION + "|" + clientJar.toAbsolutePath() + "|" + Files.size(clientJar) + "|"
            + Files.getLastModifiedTime(clientJar).toMillis() + "|" + realKey).getBytes(StandardCharsets.UTF_8));
        md.update(Files.readAllBytes(conf));
        if (Files.isDirectory(implDir)) {
            List<Path> files;
            try (Stream<Path> s = Files.walk(implDir)) { files = s.filter(Files::isRegularFile).sorted().toList(); }
            for (Path f : files) { md.update(implDir.relativize(f).toString().getBytes(StandardCharsets.UTF_8)); md.update(Files.readAllBytes(f)); }
        }
        return HexFormat.of().formatHex(md.digest());
    }

    private static void deleteTree(Path p) throws IOException {
        if (!Files.exists(p)) return;
        try (Stream<Path> s = Files.walk(p)) {
            for (Path f : s.sorted(Comparator.reverseOrder()).toList()) Files.delete(f);
        }
    }

    public void readConfig(List<String> lines) throws Exception {
        Map<String, List<String>> impls = new LinkedHashMap<>();
        for (String line : lines) {
            line = line.trim();
            if (line.isEmpty() || line.startsWith("#")) continue;
            String[] p = line.split("\\s+");
            switch (p[0]) {
                case "class" -> roots.add(p[1]);
                case "impl" -> impls.computeIfAbsent(p[1], k -> new ArrayList<>()).add(p[2]);
                case "native" -> how.put(p[1], "native");
                case "statics" -> statics.add(p[1]);
                case "keep" -> how.put(p[1], "keep");
                case "noop" -> how.put(p[1], "noop");
                case "getter" -> { int eq = p[1].indexOf('='); how.put(p[1].substring(0, eq), "getter=" + p[1].substring(eq + 1)); }
                case "mixin" -> {
                    if (mod == null) throw new IllegalArgumentException("mixin line without a mod jar: " + line);
                    ClassNode mx = read(mod, p[1]);
                    AnnotationNode an = find(mx.invisibleAnnotations, "Lorg/spongepowered/asm/mixin/Mixin;"); // CLASS retention
                    if (an == null) an = find(mx.visibleAnnotations, "Lorg/spongepowered/asm/mixin/Mixin;");
                    if (an == null) throw new IllegalStateException("no @Mixin on " + p[1]);
                    @SuppressWarnings("unchecked") List<Type> targets = (List<Type>) value(an, "value", List.of());
                    for (Type t : targets) mixinsByTarget.computeIfAbsent(t.getInternalName(), k -> new ArrayList<>()).add(mx);
                }
                default -> throw new IllegalArgumentException("proxies.conf: " + line);
            }
        }
        for (var e : impls.entrySet()) {
            for (String implName : e.getValue()) {
                ClassNode impl = readFile(implDir.resolve(implName + ".class"));
                for (MethodNode m : impl.methods) {
                    if ((m.access & (ACC_PUBLIC | ACC_STATIC)) != (ACC_PUBLIC | ACC_STATIC)) continue;
                    implCandidates.computeIfAbsent(e.getKey() + "#" + m.name, k -> new ArrayList<>()).add(new String[]{implName, m.desc});
                }
            }
        }
    }

    private boolean inJar(String n) { return n != null && client.getEntry(n + ".class") != null; }

    public String run(Path out) throws Exception {
        Deque<String> todo = new ArrayDeque<>(roots);
        Set<String> all = new LinkedHashSet<>();
        while (!todo.isEmpty()) {
            String n = todo.poll();
            if (!inJar(n) || all.contains(n)) continue;
            ClassNode cn = read(client, n);
            boolean iface = (cn.access & ACC_INTERFACE) != 0;
            if (iface && real.test(n) && !roots.contains(n)) continue; // real tier-3 interface: keep vanilla's
            all.add(n);
            todo.add(cn.superName);
            if (cn.interfaces != null) todo.addAll(cn.interfaces);
        }
        for (String n : all) {
            if (real.test(n) && !roots.contains(n)) report.append("WARNING superclass shadows a tier-3 class: ").append(n).append('\n');
            generate(read(client, n), out);
        }
        String s = String.format("generated %d classes, %d methods: %d impl, %d native, %d getter, %d noop, %d kept, %d stub; merged %d mixin members",
            classes, methods, implCount, natives, getters, noops, kept, stubs, merged);
        report.insert(0, s + "\n");
        return s;
    }

    private ClassNode read(ZipFile z, String internal) throws IOException {
        String key = z.getName() + "!" + internal;
        ClassNode cn = cache.get(key);
        if (cn != null) return cn;
        ZipEntry e = z.getEntry(internal + ".class");
        if (e == null) throw new IllegalArgumentException("not in " + z.getName() + ": " + internal);
        try (InputStream in = z.getInputStream(e)) { cn = new ClassNode(); new ClassReader(in).accept(cn, 0); }
        cache.put(key, cn);
        return cn;
    }

    private static ClassNode readFile(Path p) throws IOException {
        if (!Files.isRegularFile(p)) throw new IllegalArgumentException("impl class not compiled: " + p);
        ClassNode cn = new ClassNode();
        new ClassReader(Files.readAllBytes(p)).accept(cn, ClassReader.SKIP_CODE);
        return cn;
    }

    private void generate(ClassNode src, Path out) throws IOException {
        ClassNode g = new ClassNode();
        g.version = V21;
        g.access = src.access & ~ACC_RECORD;
        g.name = src.name;
        g.superName = src.superName;
        g.interfaces = new ArrayList<>(src.interfaces);
        boolean iface = (src.access & ACC_INTERFACE) != 0;
        if (!inJar(src.superName) && !iface) g.fields.add(new FieldNode(ACC_PUBLIC, "haste$handle", "J", null, null));
        for (FieldNode f : src.fields) {
            boolean st = (f.access & ACC_STATIC) != 0;
            // statics lose their initialiser (no <clinit>) unless they are compile-time constants: make them settable
            // (interface fields must stay public static final: they simply stay null)
            int acc = st ? (f.value != null || iface ? f.access : f.access & ~ACC_FINAL) : f.access & ~ACC_FINAL;
            g.fields.add(new FieldNode(acc, f.name, f.desc, null, st ? f.value : null));
        }
        boolean hasNoArg = false;
        boolean keepStatics = statics.contains(src.name);
        for (MethodNode m : src.methods) {
            if (m.name.equals("<clinit>")) {
                if (keepStatics) { g.methods.add(m); report.append("clinit ").append(src.name).append('\n'); }
                continue;
            }
            boolean st = (m.access & ACC_STATIC) != 0;
            String k = src.name + "#" + m.name + m.desc;
            boolean keep = "keep".equals(how.get(k)) || "keep".equals(how.get(src.name + "#" + m.name));
            boolean configured = how.containsKey(k) || findImpl(src.name, m, st) != null;
            if ((keepStatics && st && !configured && (m.access & ACC_NATIVE) == 0) || (keep && (m.access & ACC_ABSTRACT) == 0)) {
                // vanilla's own body (static helpers and lambdas of a class whose statics are kept, or a `keep` line)
                g.methods.add(m); methods++; kept++;
                report.append("keep   ").append(k).append('\n');
                continue;
            }
            MethodNode n = new MethodNode(m.access & ~(ACC_NATIVE | ACC_SYNCHRONIZED), m.name, m.desc, null,
                m.exceptions == null ? null : m.exceptions.toArray(new String[0]));
            methods++;
            if (m.name.equals("<init>")) { ctorBody(n, src); if (m.desc.equals("()V")) hasNoArg = true; }
            else if ((m.access & ACC_ABSTRACT) != 0) { /* stays abstract */ }
            else body(g, n, src.name);
            g.methods.add(n);
        }
        if (!iface && !hasNoArg) { MethodNode n = new MethodNode(ACC_PUBLIC, "<init>", "()V", null, null); ctorBody(n, src); g.methods.add(n); }
        for (ClassNode mx : mixinsByTarget.getOrDefault(src.name, List.of())) merge(g, mx);
        // Generated bodies are straight-line (no frames needed); kept vanilla bodies carry their own frames.
        ClassWriter cw = new ClassWriter(ClassWriter.COMPUTE_MAXS);
        g.accept(cw);
        Path p = out.resolve(src.name + ".class");
        Files.createDirectories(p.getParent());
        Files.write(p, cw.toByteArray());
        classes++;
    }

    /** Every generated constructor ignores its arguments and chains to the superclass no-arg constructor. */
    private static void ctorBody(MethodNode n, ClassNode src) {
        InsnList l = n.instructions;
        l.add(new VarInsnNode(ALOAD, 0));
        if ("java/lang/Enum".equals(src.superName)) {
            l.add(new LdcInsnNode("haste")); l.add(new InsnNode(ICONST_0));
            l.add(new MethodInsnNode(INVOKESPECIAL, "java/lang/Enum", "<init>", "(Ljava/lang/String;I)V", false));
        } else {
            l.add(new MethodInsnNode(INVOKESPECIAL, src.superName, "<init>", "()V", false));
        }
        l.add(new InsnNode(RETURN));
    }

    private void body(ClassNode g, MethodNode n, String owner) {
        String key = owner + "#" + n.name + n.desc;
        Type ret = Type.getReturnType(n.desc);
        boolean isStatic = (n.access & ACC_STATIC) != 0;
        InsnList l = n.instructions;
        String kind = how.get(key);
        String[] impl = kind == null ? findImpl(owner, n, isStatic) : null;
        if (kind == null && impl == null) kind = how.get(owner + "#*");
        if (impl != null) {
            implCount++;
            int slot = 0;
            if (!isStatic) { l.add(new VarInsnNode(ALOAD, 0)); slot = 1; }
            for (Type at : Type.getArgumentTypes(n.desc)) { l.add(new VarInsnNode(at.getOpcode(ILOAD), slot)); slot += at.getSize(); }
            l.add(new MethodInsnNode(INVOKESTATIC, impl[0], n.name, impl[1], false));
            Type implRet = Type.getReturnType(impl[1]);
            if (!implRet.equals(ret) && (ret.getSort() == Type.OBJECT || ret.getSort() == Type.ARRAY))
                l.add(new TypeInsnNode(CHECKCAST, ret.getInternalName()));
            l.add(new InsnNode(ret.getOpcode(IRETURN)));
            report.append("impl   ").append(key).append(" -> ").append(impl[0]).append('\n');
        } else if (kind == null) {
            stubs++;
            l.add(new LdcInsnNode(key));
            l.add(new MethodInsnNode(INVOKESTATIC, "haste/rt/Unimplemented", "fail", "(Ljava/lang/String;)Ljava/lang/RuntimeException;", false));
            l.add(new InsnNode(ATHROW));
        } else if (kind.equals("native")) {
            natives++;
            n.access |= ACC_NATIVE;
            report.append("native ").append(key).append('\n');
        } else if (kind.equals("noop")) {
            noops++;
            switch (ret.getSort()) {
                case Type.VOID -> {}
                case Type.LONG -> l.add(new InsnNode(LCONST_0));
                case Type.FLOAT -> l.add(new InsnNode(FCONST_0));
                case Type.DOUBLE -> l.add(new InsnNode(DCONST_0));
                case Type.OBJECT, Type.ARRAY -> l.add(new InsnNode(ACONST_NULL));
                default -> l.add(new InsnNode(ICONST_0));
            }
            l.add(new InsnNode(ret.getOpcode(IRETURN)));
            report.append("noop   ").append(key).append('\n');
        } else if (kind.startsWith("getter=")) {
            getters++;
            String spec = kind.substring(7), field = spec, desc = ret.getDescriptor();
            if (spec.contains(":")) { field = spec.substring(0, spec.indexOf(':')); desc = spec.substring(spec.indexOf(':') + 1); }
            final String fd = field;
            if (g.fields.stream().noneMatch(f -> f.name.equals(fd))) g.fields.add(new FieldNode(ACC_PUBLIC, field, desc, null, null));
            l.add(new VarInsnNode(ALOAD, 0));
            l.add(new FieldInsnNode(GETFIELD, g.name, field, desc));
            l.add(new InsnNode(ret.getOpcode(IRETURN)));
            report.append("getter ").append(key).append(" = ").append(field).append('\n');
        }
    }

    /** An impl method with the same name whose descriptor is {@code (Owner, args)ret} (instance) or {@code (args)ret} (static). */
    private String[] findImpl(String owner, MethodNode n, boolean isStatic) {
        List<String[]> cands = implCandidates.get(owner + "#" + n.name);
        if (cands == null) return null;
        Type[] args = Type.getArgumentTypes(n.desc);
        Type ret = Type.getReturnType(n.desc);
        int off = isStatic ? 0 : 1;
        for (String[] c : cands) {
            Type[] ca = Type.getArgumentTypes(c[1]);
            if (ca.length != args.length + off) continue;
            if (!isStatic && !ca[0].getDescriptor().equals("L" + owner + ";")) continue;
            boolean ok = true;
            for (int i = 0; i < args.length && ok; i++) ok = ca[i + off].equals(args[i]);
            if (ok && Type.getReturnType(c[1]).equals(ret)) return c;
        }
        return null;
    }

    /** Non-shadow fields, added interfaces and plain methods of a mixin become members of the proxy (like real Mixin). */
    private void merge(ClassNode g, ClassNode mx) {
        SimpleRemapper rm = new SimpleRemapper(mx.name, g.name);
        for (String i : mx.interfaces) if (!g.interfaces.contains(i)) { g.interfaces.add(i); merged++; }
        for (FieldNode f : mx.fields) {
            if (has(f.visibleAnnotations, f.invisibleAnnotations, "Lorg/spongepowered/asm/mixin/Shadow;")) continue;
            g.fields.add(new FieldNode(f.access, f.name, f.desc, null, f.value)); merged++;
        }
        for (MethodNode m : mx.methods) {
            if (m.name.equals("<init>") || has(m.visibleAnnotations, m.invisibleAnnotations, "Lorg/spongepowered/asm/mixin/injection/Inject;")
                || has(m.visibleAnnotations, m.invisibleAnnotations, "Lorg/spongepowered/asm/mixin/Shadow;")) continue;
            MethodNode n = new MethodNode(m.access, m.name, m.desc, null, m.exceptions == null ? null : m.exceptions.toArray(new String[0]));
            m.accept(new MethodRemapper(n, rm));
            g.methods.add(n); merged++;
        }
    }

    private static boolean has(List<AnnotationNode> a, List<AnnotationNode> b, String d) { return find(a, d) != null || find(b, d) != null; }
    private static AnnotationNode find(List<AnnotationNode> l, String d) { if (l == null) return null; for (AnnotationNode a : l) if (d.equals(a.desc)) return a; return null; }
    private static Object value(AnnotationNode a, String k, Object dflt) { if (a == null || a.values == null) return dflt; for (int i = 0; i < a.values.size(); i += 2) if (k.equals(a.values.get(i))) return a.values.get(i + 1); return dflt; }

    /** CLI: {@code Gen <client.jar> <proxies.conf> <implDir> <outDir> [mod.jar]} (Haste itself calls {@link #generateIfStale}). */
    public static void main(String[] a) throws Exception {
        Gen g = new Gen(Path.of(a[0]), a.length > 4 ? Path.of(a[4]) : null, Path.of(a[2]), n -> false);
        g.readConfig(Files.readAllLines(Path.of(a[1])));
        System.out.println(g.run(Path.of(a[3])));
    }
}

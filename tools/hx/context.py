"""hx context BRIEF: the orientation pack a worker starts with. Every vanilla class and method
the brief names is resolved to its file and line range (short methods printed in full), with the
Haste code that already cites it; every Haste path the brief names gets its size and summary.
It replaces the first dozens of searches a worker would otherwise spend finding these."""
import os
import re

import data
import haste
import vanilla
from common import ROOT, clip, out, rg

NAME = re.compile(r"\b([A-Z][A-Za-z0-9]+(?:\.[A-Z][A-Za-z0-9]+)*)(?:\.([a-z][A-Za-z0-9]*))?\b")
PATH = re.compile(r"\b((?:crates|scripts|tools|docs)/[\w./-]+)")
BODY_MAX = 30     # print a named method in full when it is at most this long
BODIES_TOTAL = 140


def cited_by(name, n=3):
    hits = rg(["-l", "-e", rf"//.*\b{re.escape(name)}\b", "crates"])
    return sorted(hits)[:n], len(hits)


SUFFIXES = ("Renderer", "Model", "Layer", "Screen", "Packet", "Handler", "Manager")
WORD = re.compile(r"\b[a-z][a-z_]{4,}\b")


def snake(name):
    for suf in SUFFIXES:
        if name.endswith(suf) and name != suf:
            name = name[: -len(suf)]
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def task_section(text):
    """The brief's own task text ("What to port"/"What to do"), without the shared rules."""
    m = re.search(r"^## What to (?:port|do|build|fix)\b.*?$(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1) if m else text


def concept_files(text, names, limit=15):
    """Haste files named after a concept the task mentions (files follow vanilla's concepts:
    `ArmorStandRenderer` -> armor_stand.rs, "equipment layers" -> equipment.rs): the existing
    seams a task should plug into. Vanilla-name matches first, then the task's own words."""
    task = task_section(text)
    strong = {snake(c.split(".")[-1]) for c, _, _ in names if c in task}
    weak = set(WORD.findall(task.lower())) - strong
    hits = []
    for r, dirs, fs in os.walk(os.path.join(ROOT, "crates")):
        dirs[:] = [d for d in dirs if d not in ("target", "tests")]
        for f in fs:
            stem = f[:-3]
            if f.endswith(".rs") and stem not in ("mod", "lib", "main", "tests"):
                rank = 0 if stem in strong else 1 if stem in weak else None
                if rank is not None:
                    hits.append((rank, os.path.relpath(os.path.join(r, f), ROOT)))
    if not hits:
        return strong
    out("Existing Haste files named after concepts in the task (plug into these; "
        "`hx outline FILE`):")
    for _, p in sorted(hits)[:limit]:
        full = os.path.join(ROOT, p)
        out(f"- {p} ({haste.count_lines(full)} lines) {clip(haste.module_doc(full), 110)}")
    return strong


def game_data(stems, limit=4):
    """The game data on the task's concepts (`ArmorStandRenderer` -> armor_stand): model layers,
    sizes and registry ids the work builds on, so nobody concludes they are missing."""
    shown = False
    names = set()
    for stem in stems or ():
        for suffix in ("_renderer", "_model", "_layer", "_screen", "_armor"):
            stem = stem.removesuffix(suffix)
        names.add(stem)
    for stem in sorted(names):
        found = data.lookup(stem, limit) if data.is_game_id(stem) else None
        if not found:
            continue
        if not shown:
            out("Game data on those concepts (`hx data NAME`; Haste reads these dumps at runtime):")
            shown = True
        data.print_lookup(stem, found, limit)


def cmd_context(brief_path):
    text = open(brief_path, encoding="utf-8").read()
    seen, names = set(), []
    for m in NAME.finditer(text):
        key = m.group(0)
        if key not in seen:
            seen.add(key)
            ticked = text[max(0, m.start() - 1):m.start()] == "`"
            names.append((m.group(1), m.group(2), ticked))
    budget = BODIES_TOTAL
    out("## Orientation pack (generated by `hx context` from the brief)")
    out("Vanilla names in the brief, resolved in cache/source/26.3/client "
        "(`hx vanilla Class.method` prints any method):")
    shown = 0
    for cls, meth, ticked in names:
        if not meth and not ticked and sum(c.isupper() for c in cls) < 2:
            continue  # a capitalised English word ("Report", "Unit"), not a class name
        paths, rest = vanilla.resolve(cls)
        if not paths:
            continue
        label = cls + (f".{meth}" if meth else "")
        files, total = cited_by(label if meth else cls)
        cite = (f"; Haste cites it in {', '.join(files)}" + (f" (+{total - len(files)})"
                if total > len(files) else "")) if files else "; not cited in Haste yet"
        if meth:
            top = cls.split(".")[0]
            inner = [p for p in cls.split(".")[1:]]
            found = vanilla.find_method(top, meth, inner)
            if not found:
                out(f"- {label}  not found in {paths[0]} or its supertypes")
                continue
            for rel, lines, _, m in found:
                a, b = m[3], m[4]
                via = "" if rel in paths else f" (inherited, declared in {rel[:-5]})"
                out(f"- {label}  {rel}:{a + 1}-{b + 1} ({b - a + 1} lines){via}{cite}")
                if b - a + 1 <= BODY_MAX and budget >= b - a + 1:
                    budget -= b - a + 1
                    for i in range(a, b + 1):
                        out(f"  {i + 1:5} {lines[i]}")
        else:
            rel = paths[0]
            lines = vanilla.read_lines(rel)
            mems = vanilla.members(lines)
            n_methods = sum(1 for m in mems if m[0] == "method")
            out(f"- {label}  {rel} ({len(lines)} lines, {n_methods} methods){cite}")
        shown += 1
    if not shown:
        out("  (the brief names no vanilla class)")
    stems = concept_files(text, names)
    game_data(stems)
    paths = sorted({p.rstrip(".,:;)`/") for p in PATH.findall(text)})
    if paths:
        out("Haste paths in the brief:")
        for p in paths:
            full = os.path.join(ROOT, p)
            if os.path.isfile(full):
                doc = haste.module_doc(full) if p.endswith(".rs") else ""
                out(f"- {p} ({haste.count_lines(full)} lines) {clip(doc, 110)}")
            elif os.path.isdir(full):
                out(f"- {p}/ (directory: `hx map {p}`)")
            else:
                out(f"- {p} (does not exist yet)")
